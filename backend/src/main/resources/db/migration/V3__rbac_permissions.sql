-- Map Permissions to ROLE_CUSTOMER
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.role_name = 'ROLE_CUSTOMER'
  AND p.permission_name IN (
      'AUTH_ME',
      'AUTH_CHANGE_PASSWORD',
      'USER_READ_SELF',
