  /// Lấy danh mục theo mã ID
  static ComponentCategory? getCategoryById(String id) {
    try {
      return categories.firstWhere((cat) => cat.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Lấy các linh kiện thuộc loại linh kiện cụ thể (cpu, gpu, ram, ...)
  static List<Product> getByComponentType(String componentType) {
    return products.where((p) => p.componentType == componentType).toList();
  }

  /// Lấy sản phẩm theo tên danh mục chính ('Linh Kiện PC', 'PC Gaming', 'Laptop Gaming', ...)
  static List<Product> getByCategory(String category) {
    return products.where((p) => p.category.toLowerCase() == category.toLowerCase()).toList();
  }

  /// Lấy danh sách linh kiện phục vụ cho việc Build PC trọn bộ
  static List<Product> getBuildPcComponents() {
    const buildTypes = {'cpu', 'mainboard', 'ram', 'gpu', 'storage', 'psu', 'cooler', 'case'};
    return products.where((p) => p.componentType != null && buildTypes.contains(p.componentType)).toList();
  }

  /// Lấy danh sách sản phẩm nổi bật
  static List<Product> getFeaturedProducts() {
    return products.where((p) => p.isFeatured).toList();
  }

  /// Tìm kiếm sản phẩm theo từ khóa (tên, hãng, danh mục, loại linh kiện, thông số kỹ thuật)
  static List<Product> searchProducts(String query) {
    if (query.trim().isEmpty) return products;
    final q = query.trim().toLowerCase();
    return products.where((p) {
      final inName = p.name.toLowerCase().contains(q);
      final inBrand = p.brand.toLowerCase().contains(q);
      final inDesc = p.description.toLowerCase().contains(q);
      final inCategory = p.category.toLowerCase().contains(q);
      final inComponentType = p.componentType?.toLowerCase().contains(q) ?? false;
      final inSpecs = p.specs.any((s) => s.toLowerCase().contains(q));
      final inTechSpecs = p.technicalSpecs.entries.any(
        (e) => e.key.toLowerCase().contains(q) || e.value.toLowerCase().contains(q),
      );
      return inName || inBrand || inDesc || inCategory || inComponentType || inSpecs || inTechSpecs;
    }).toList();
  }

  /// Lọc sản phẩm thông minh theo bộ lọc danh mục hoặc loại linh kiện
  static List<Product> filterProducts(String filter) {
    final f = filter.trim();
    if (f.isEmpty || f.toLowerCase() == 'tất cả') return products;

    // 1. Khớp chính xác hoặc gần đúng theo ComponentCategory id
    final byType = getByComponentType(f.toLowerCase());
    if (byType.isNotEmpty) return byType;

    // 2. Khớp theo ComponentCategory shortName hoặc name
    for (final cat in categories) {
      if (cat.shortName.toLowerCase() == f.toLowerCase() ||
          cat.name.toLowerCase() == f.toLowerCase() ||
          cat.id.toLowerCase() == f.toLowerCase()) {
        return getByComponentType(cat.id);
      }
    }

    // 3. Khớp theo danh mục chính hoặc từ khóa đặc biệt
    final fLower = f.toLowerCase();
    if (fLower == 'linh kiện pc' || fLower == 'linh-kien-pc') {
      return products.where((p) => p.category == 'Linh Kiện PC').toList();
    }
    if (fLower == 'pc gaming' || fLower == 'pc-gaming') {
      return products.where((p) => p.category == 'PC Gaming').toList();
    }
    if (fLower.contains('đồ họa') || fLower == 'pc-do-hoa') {
      return products.where((p) => p.category.contains('Đồ Họa')).toList();
    }
    if (fLower.contains('laptop') || fLower == 'laptop-gaming') {
      return products.where((p) => p.componentType == 'laptop' || p.category.contains('Laptop')).toList();
    }
    if (fLower.contains('màn hình') || fLower == 'man-hinh-gaming') {
      return products.where((p) => p.componentType == 'monitor' || p.category.contains('Màn Hình')).toList();
    }
    if (fLower.contains('gear') || fLower == 'gear-gaming') {
      return products.where((p) => p.componentType == 'gear' || p.category.contains('Gear')).toList();
    }
    if (fLower.contains('khuyến mãi') || fLower == 'sale') {
      return products.where((p) => p.discountPercentage > 0).toList();
    }
    if (fLower == 'rtx 5080') {
      return products.where((p) => p.name.contains('RTX 5080') || p.componentType == 'gpu').toList();
    }
    if (fLower == 'ps5 slim' || fLower == 'ps5') {
      return products.where((p) => p.name.contains('PS5') || p.componentType == 'gear').toList();
    }

    // 4. Fallback search
    return searchProducts(f);
  }
